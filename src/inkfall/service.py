def new_request_id() -> str:
    return uuid.uuid4().hex[:16]


def _texts(views: dict[int, VersionView]) -> dict[int, str]:
    return {vid: v.version.text for vid, v in views.items()}


def run_query(session: Session, user: User, directory: Directory, question: str, as_of: dt.date,
              method: str = "hybrid", collection: str | None = None, include_history: bool = False,
              generate_mode: str = "extractive", k: int = 50) -> dict:
    """The full evidence pipeline. Returns a JSON-able dict (also used by the eval harness)."""
    t0 = time.perf_counter()
    question = normalize_query(question)
    views_list = authorized_versions(session, user, directory, as_of, include_history, collection)
    views = {v.version.id: v for v in views_list}
    sr = search(session, user.tenant, question, views_list, method, k)
    pack = ev.build_pack(session, sr.hits, views)
    texts = _texts(views)
    extractive = ev.extractive_answer(question, pack, texts)
    assessment = ev.assess(question, pack, extractive)
    conflicts, overrides = ev.find_conflicts(question, pack, texts)
    query_injection = ev.detect_injection(question)
    answer = extractive
    mode = "extractive"
    gen_info: dict = {"requested": generate_mode != "extractive"}
    if generate_mode != "extractive" and pack and not assessment.abstained:
        provider = get_provider(None if generate_mode == "generative" else generate_mode)
        if provider is None:
            gen_info["status"] = "no local model detected; showing extractive evidence"
        else:
            g = generate(provider, question, pack, texts)
            gen_info.update(status="ok" if g.ok else "rejected", rejected_reason=g.rejected_reason, model=g.model,
                            provider=g.provider, latency_ms=round(g.latency_ms, 1),
                            prompt_tokens_est=g.prompt_tokens_est, completion_tokens_est=g.completion_tokens_est,
                            usage_reported=g.usage_reported, model_abstained=g.abstained, raw_output=g.raw_output,
                            cost_note="local model: $0 billed; token counts are chars/4 estimates")
            if g.ok and g.sentences:
                answer, mode = g.sentences, "generative"
    if assessment.abstained:
        answer = []
    status = "insufficient_evidence" if assessment.abstained else ("contradictory" if conflicts else "supported")
    if mode == "generative" and any(s.support == "unsupported" for s in answer):
        status = "partially_unsupported"
    injection_passages = [{"pid": p.pid, "ref": p.ref, "matches": p.injection_flags} for p in pack if p.injection_flags]
    graph = ev.evidence_graph(pack, views, answer, conflicts)
    total_ms = (time.perf_counter() - t0) * 1000
    return {
        "question": question,
        "as_of": as_of.isoformat(),
        "scope": {"tenant": user.tenant, "collection": collection, "include_history": include_history,
                  "authorized_versions": len(views_list), "authorized_chunks": sr.candidates},
        "status": status,
        "mode": mode,
        "mode_label": ("Extractive evidence: verbatim source sentences, no language model" if mode == "extractive"
                       else f"Generated by local model {gen_info.get('model')} via {gen_info.get('provider')}; "
                            "each sentence checked against its cited passages"),
        "answer": [asdict(s) for s in answer],
        "abstained": assessment.abstained,
        "abstain_reason": assessment.abstain_reason,
        "trust": {
            "evidence_coverage": round(assessment.coverage, 3),
            "matched_terms": assessment.matched_terms,
            "missing_terms": assessment.missing_terms,
            "gaps": assessment.gaps,
            "conflicts": [asdict(c) for c in conflicts],
            "amendment_overrides": overrides,
            "freshness": ev.freshness(pack, as_of),
            "untrusted_instructions_in_sources": injection_passages,
            "untrusted_instructions_in_question": query_injection,
            "note": "Coverage = share of the question's key terms found in the top authorized passages. "
                    "It is a diagnostic, not a probability that the answer is correct.",
        },
        "retrieval": {"method": sr.method, "notes": sr.notes, "latency_ms": round(sr.latency_ms, 1),
                      "hits": [{"chunk_id": h.chunk_id, "version_id": h.version_id, "rank": h.rank,
                                "components": h.components} for h in sr.hits[:10]]},
        "sources": [asdict(p) for p in pack],
        "graph": graph,
        "generation": gen_info,
        "latency_ms": round(total_ms, 1),
        "ranked_version_ids": _ranked(sr.hits),
        "ranked_refs": [views[vid].ref for vid in _ranked(sr.hits)],
    }


def _ranked(hits) -> list[int]:
    seen: list[int] = []
    for h in hits:
        if h.version_id not in seen:
            seen.append(h.version_id)
    return seen


def verify_citation(session: Session, user: User, directory: Directory, version_id: int, start: int, end: int,
                    quote: str | None = None) -> tuple[bool, str]:
    """A citation is valid only if the caller may read the version and the span matches stored text."""
    view = get_authorized_version(session, user, directory, version_id)
    if view is None:
        return False, "version not found"
    body = view.version.text
    if not (0 <= start < end <= len(body)):
        return False, "span out of range"
    if quote is not None and body[start:end] != quote:
        return False, "quote does not match stored source text"
    return True, "ok"


def document_payload(view: VersionView, history: list[VersionView]) -> dict:
    v, d = view.version, view.document
    return {
        "version_id": v.id, "ref": view.ref, "doc_key": d.doc_key, "version": v.version, "title": v.title,
        "collection": d.collection, "doc_type": d.doc_type, "matter": d.matter, "effective_date": v.effective_date.isoformat(),
        "classification": v.classification, "parties": v.parties, "tags": v.tags, "amends": v.amends_key,
        "text": v.text,
        "chunks": [{"chunk_id": c.id, "heading": c.heading, "char_start": c.char_start, "char_end": c.char_end}
                   for c in v.chunks],
        "lineage": {
            "checksum_sha256": v.checksum, "ingested_at": v.ingested_at.isoformat() + "Z", "ingested_by": v.ingested_by,
            "source_filename": v.source_filename, "source_mime": v.source_mime,
            "extraction_method": v.extraction_method, "byte_size": v.byte_size, "retention": v.retention,
            "in_force_today": view.in_force, "superseded_by_version": view.superseded_by,
        },
        "access": {"decision": "allowed", "reasons": list(view.decision.reasons),
                   "acl_groups": v.acl_groups, "ethical_wall_applies": bool(v.ethical_wall)},
        "versions": [{"version_id": h.version.id, "version": h.version.version,
                      "effective_date": h.version.effective_date.isoformat()} for h in history],
    }


def compare_versions(a: VersionView, b: VersionView) -> dict:
    """Clause-level diff between two authorized versions of the same document."""
    def clauses(view: VersionView) -> list[dict]:
        return [{"heading": c.heading, "text": c.text, "char_start": c.char_start, "char_end": c.char_end}
                for c in view.version.chunks]

    ca, cb = clauses(a), clauses(b)
    sm = difflib.SequenceMatcher(a=[c["text"] for c in ca], b=[c["text"] for c in cb], autojunk=False)
    ops = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            ops.append({"op": "equal", "count": i2 - i1})
            continue
        left, right = ca[i1:i2], cb[j1:j2]
        pairs = []
        for k in range(max(len(left), len(right))):
            lc = left[k] if k < len(left) else None
            rc = right[k] if k < len(right) else None
            words = None
            if lc and rc:
                words = [{"op": t, "a": " ".join(lc["text"].split()[x1:x2]), "b": " ".join(rc["text"].split()[y1:y2])}
                         for t, x1, x2, y1, y2 in difflib.SequenceMatcher(
                             a=lc["text"].split(), b=rc["text"].split(), autojunk=False).get_opcodes() if t != "equal"]
                lv, rv = ev.extract_values(lc["text"]), ev.extract_values(rc["text"])
                value_changes = {k2: {"from": sorted(lv[k2]), "to": sorted(rv[k2])}
                                 for k2 in lv if lv[k2] != rv[k2] and (lv[k2] or rv[k2])}
            else:
                value_changes = {}
            pairs.append({"left": lc, "right": rc, "word_changes": words, "value_changes": value_changes})
        ops.append({"op": tag, "pairs": pairs})
    return {"a": {"ref": a.ref, "version_id": a.version.id, "effective_date": a.version.effective_date.isoformat()},
            "b": {"ref": b.ref, "version_id": b.version.id, "effective_date": b.version.effective_date.isoformat()},
            "ops": ops,
            "method": "difflib clause alignment + typed value extraction (money, %, durations, dates)"}
