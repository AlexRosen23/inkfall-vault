def faithfulness_section(fa) -> list[str]:
    if not fa:
        return ["## Answer faithfulness (LLM judge)", "", "Not run in this report.", ""]
    pv, dm = fa["provenance"], fa["deterministic_metrics_natural"]

    def cm(c):
        return (f"{c['n']} | {c['ref_pass']} / {c['ref_fail']} | {f(c['tpr'])} ({c['tp']}/{c['ref_pass']}) | "
                f"{f(c['tnr'])} ({c['tn']}/{c['ref_fail']}) | {f(c['agreement'])}")
    out = ["## Answer faithfulness: binary LLM judge calibrated against reference labels", "",
           f"_From `eval/reports/faithfulness.json` ({fa['generated_at']}, commit `{pv['git_commit']}`); answers from "
           f"`{pv['answers_file']}` ({pv['answers_generated_at']})._", "",
           f"**Criterion:** {fa['criterion']}. Positive class = PASS. Method after Hamel Husain's LLM-judge guide: "
           "binary verdict with a written critique, labels split into judge-dev (answers to dev-split gold questions) "
           "and judge-test (test-split questions), prompt changed only after reading judge-dev disagreements, then "
           "frozen and run once on judge-test; true-positive and true-negative rates reported separately.", "",
           f"- Generator: **{pv['generator']['model']}** via {pv['generator']['provider']} (local). Judge: the **same "
           f"model** with a different prompt (`{pv['judge_prompt']}`). **Limitation:** a judge that shares the "
           "generator's model can share its blind spots (self-preference). On judge-test every FAIL label is a synthetic "
           "negative, so the TNR says how well the judge catches changed numbers and fabricated sentences, not subtle "
           "natural misreadings.",
           "- Prompt iteration: v2 added three rules after reading the v1 judge-dev disagreements. Aggregate dev "
           "agreement did not change (the disagreements moved to different items), so the tie was broken in favour of "
           "the more explicit v2, which was then frozen before the single judge-test run.",
           f"- Reference labels: `{pv['labels_file']}`, **{pv['labeler']}**. They were written blind (opaque ids, "
           "shuffled) by a separate Claude Code subagent from a written rubric; they are not human expert labels. "
           "Agreement below is agreement with AI-drafted reference labels. 30 items are in "
           "`eval/faithfulness/owner_review.csv` for the owner to confirm.",
           f"- Labels: {fa['label_counts']['total']} ({fa['label_counts']['pass']} PASS, {fa['label_counts']['fail']} FAIL). "
           "Natural answers were almost all faithful, so seeded synthetic negatives (a changed number, or an appended "
           "fabricated sentence citing the same passage) were added; they are reported separately.", "",
           "| Split / subset | Grader | n | ref PASS / FAIL | TPR | TNR | Agreement |", "|---|---|---|---|---|---|---|"]
    for v, blk in fa["dev_iterations"].items():
        out.append(f"| judge-dev, all (prompt {v}) | LLM judge | {cm(blk['all']['judge'])} |")
    for sub in ("all", "natural", "synthetic"):
        out.append(f"| **judge-test, {sub}** | LLM judge | {cm(fa['test'][sub]['judge'])} |")
        out.append(f"| judge-test, {sub} | deterministic span check | {cm(fa['test'][sub]['deterministic'])} |")
    pr = fa["test_pass_rates_natural"]
    out += ["", f"Pass rate on natural judge-test answers: reference labels {f(pr['reference_labels'], True)}, judge raw "
                f"{f(pr['judge_raw'], True)}, judge corrected for its measured TPR/TNR "
                f"{f(pr['judge_corrected'], True) if pr['judge_corrected'] is not None else 'n/a'} "
                "(Rogan-Gladen; optimistic, because the TNR it uses comes from synthetic negatives).", "",
            "**Deterministic metrics on the same natural answers** (existing code grader, `generate.support_level`; no LLM):", "",
            f"- {dm['natural_answers']} generated answers ({dm['skipped_questions']} gold questions produced no generated "
            "answer: abstained before the model was called, or the model abstained).",
            f"- Sentences: {dm['sentences']} — supported {dm['sentence_support']['supported']}, partial "
            f"{dm['sentence_support']['partial']}, unsupported {dm['sentence_support']['unsupported']}.",
            f"- Answers with every sentence 'supported': {dm['answers_all_sentences_supported']}/{dm['natural_answers']}; "
            f"answers containing a gold answer span: {dm['answers_with_gold_span']}/{dm['natural_answers']}.",
            f"- Citations re-verified against stored text + ACL: {dm['citations_reverified_ok']}/{dm['citations_total']}.",
            f"- Latency: generation p50 {fa['latency_ms']['generation_p50']} ms (max {fa['latency_ms']['generation_max']}); "
            f"judge p50 {fa['latency_ms']['judge_p50']} ms. Judge parse errors on test: {fa['judge_parse_errors_test']}.", "",
            "Reading the two graders together: the deterministic check is strict about surface form, so it marks "
            "faithful paraphrases ('USD 30 million' for 'USD 30,000,000') and derived values (a computed monthly bill) "
            "as unsupported; the LLM judge accepts those but has to be measured against labels before its pass rate "
            "means anything.", ""]
    return out


