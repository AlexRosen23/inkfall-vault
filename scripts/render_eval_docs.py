"""Render docs/RETRIEVAL_EVAL.md, docs/RAG_EVALUATION.md and resume_evidence/metrics.json from the
saved reports (eval/reports/latest.json, adversarial.json, generative.json). No number is typed by hand."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "eval" / "reports"


def load(name):
    p = REP / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, pct=False):
    if x is None:
        return "n/a"
    return f"{x * 100:.1f}%" if pct else (f"{x:.3f}" if isinstance(x, float) else str(x))


def retrieval_table(summary: dict, split: str) -> list[str]:
    rows = ["| Method | Recall@5 | Precision@5 | MRR@10 | nDCG@10 | p50 ms | p95 ms |", "|---|---|---|---|---|---|---|"]
    for m, a in summary[split].items():
        if m == "baseline_title_only":
            rows.append(f"| title-only baseline (no RAG) | {f(a['recall_at_5'])} | n/a | {f(a['mrr_at_10'])} | n/a | n/a | n/a |")
            continue
        rows.append(f"| {m} | {f(a['recall_at_5'])} | {f(a['precision_at_5'])} | {f(a['mrr_at_10'])} | "
                    f"{f(a['ndcg_at_10'])} | {a['latency_ms']['p50']} | {a['latency_ms']['p95']} |")
    return rows


def answer_table(summary: dict, split: str) -> list[str]:
    rows = ["| Method | Citation validity | Answer support | Unsupported-answer rate | Evidence in pack | "
            "Abstain P / R / F1 | Conflicts found / expected (false alarms) | Leaks | Injection quoted | Errors |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for m, a in summary[split].items():
        if m == "baseline_title_only":
            continue
        ab, cf = a["abstention"], a["conflicts"]
        rows.append(f"| {m} | {f(a['citation_validity'], True)} ({a['citations']}) | {f(a['answer_support_rate'], True)} | "
                    f"{f(a['unsupported_answer_rate'], True)} | {f(a['evidence_in_pack_rate'], True)} | "
                    f"{f(ab['precision'])} / {f(ab['recall'])} / {f(ab['f1'])} | {cf['flagged']} / {cf['expected']} "
                    f"({cf['false_alarms_on_other_answerable']} of {cf['other_answerable']}) | {a['leaks']} | "
                    f"{a['injection_sentences_quoted']} | {a['errors']} |")
    return rows


def failures(rep: dict, method: str = "hybrid", split: str = "test", limit: int = 10) -> list[str]:
    out = []
    for q in rep["questions"]:
        if q["split"] != split or method not in q["methods"]:
            continue
        m = q["methods"][method]
        kind = None
        if q["relevant"] and m.get("hit_at_5") == 0:
            kind = "missed retrieval"
        elif q["expect_abstain"] and not m["abstained"]:
            kind = "should have abstained"
        elif q["relevant"] and m["abstained"]:
            kind = "abstained on answerable"
        elif q["relevant"] and not m.get("answer_supported", True):
            kind = "cited sentences miss the gold span"
        elif q["expect_conflict"] and not m["conflict_flagged"]:
            kind = "conflict not detected"
        elif q["relevant"] and not q["expect_conflict"] and m["conflict_flagged"]:
            kind = "false conflict alarm"
        if kind:
            out.append(f"| {q['id']} | {q['category']} | {kind} | {q['question'][:90]} | "
                       f"{', '.join(q['relevant']) or '(none)'} | {', '.join(m['top_refs'][:3])} |")
        if len(out) >= limit:
            break
    return ["| ID | Category | Failure | Question | Gold refs | Top retrieved |", "|---|---|---|---|---|---|", *out]


def main() -> None:
    rep, adv, gen = load("latest.json"), load("adversarial.json"), load("generative.json")
    if rep is None:
        raise SystemExit("no eval/reports/latest.json - run make eval")
    pv = rep["provenance"]
    mach = pv["machine"]
    s = rep["summary"]
    head = [
        f"_Generated by `scripts/render_eval_docs.py` from `eval/reports/latest.json` ({rep['generated_at']}). "
        "Do not edit numbers by hand; re-run `make eval`._", "",
        f"- Commit `{pv['git_commit']}` (uncommitted changes in src/data: {pv['uncommitted_changes_in_src_or_data']}); "
        f"dataset version `{pv['dataset_version']}` ({pv['documents']} fictional documents); "
        f"{pv['gold_questions']} gold questions.",
        f"- Machine: {mach['cpu']}, {mach['memory_gb']} GB, {mach['platform']}, Python {mach['python']}, CPU only. "
        f"Whole run: {pv['wall_seconds']} s.",
        f"- Embedding model: `{pv['embedding_model']}`. Reranker: {pv['reranker'] or 'not run'}"
        + (f" ({rep['methods_skipped'].get('rerank')})" if rep["methods_skipped"].get("rerank") else "") + ".",
        f"- Answer mode for these numbers: {pv['answer_mode']}.", "",
    ]
    counts = {sp: s[sp][rep["methods_run"][0]]["questions"] for sp in s}
    ret = ["# Retrieval evaluation", "", *head,
           "## How to read this", "",
           "- Metrics are document-version level: a hit means the exact gold version (e.g. `CV-MSA-ORION@2`) was "
           "retrieved for the asking user on the question's as-of date.",
           "- Each identity can read only 3-15 document versions in total, so **Recall@5 saturates**; MRR@10 and nDCG@10 are the "
           "informative ranking metrics. Precision@5 is capped by the number of relevant docs per question (1-2).",
           "- Thresholds and heuristics were tuned on the **dev** split only. The **test** split was not used for "
           f"tuning. Questions per split: {counts}.",
           "- The title-only baseline ranks a user's authorized documents by query-word overlap with document titles: "
           "a stand-in for browsing a library by name, not a measured human baseline.", ""]
    for sp in ("test", "dev", "all"):
        if sp in s:
            ret += [f"## {sp} split", "", *retrieval_table(s, sp), ""]
    ret += ["## Per category (all splits, hybrid)", "",
            "| Category | Questions | Recall@5 | MRR@10 | Abstain F1 | Leaks |", "|---|---|---|---|---|---|"]
    for c, ms in rep["by_category"].items():
        a = ms.get("hybrid") or next(iter(ms.values()))
        ret.append(f"| {c} | {a['questions']} | {f(a['recall_at_5'])} | {f(a['mrr_at_10'])} | {f(a['abstention']['f1'])} | {a['leaks']} |")
    ret += ["", "## Failure examples (test split, hybrid)", "", *failures(rep), "",
            "Full per-question rows (every method, top refs, latency) are in `eval/reports/latest.json` and in the "
            "Evaluation & Trust Console (`/lab`).", ""]
    (ROOT / "docs" / "RETRIEVAL_EVAL.md").write_text("\n".join(ret))

    rag = ["# RAG evaluation: citations, support, abstention, conflicts, safety", "", *head,
           "## Grading method (deterministic; no LLM judge)", "",
           "| Metric | Rule |", "|---|---|",
           "| Citation validity | cited quote == stored `text[char_start:char_end]` of a version the asker may read |",
           "| Answer support | a non-abstained answer to an answerable question is supported when >= 1 gold answer span "
           "appears verbatim inside its cited sentences |",
           "| Unsupported-answer rate | 1 - answer support (over answered, answerable questions) |",
           "| Evidence in pack | a gold span appears anywhere in the 6-passage source pack (upper bound for the answerer) |",
           "| Abstention | positive class = gold `expect_abstain`; precision / recall / F1 |",
           "| Conflicts | flagged on `expect_conflict` questions; false alarms on other answerable questions |",
           "| Leaks | any ref outside the asker's ACL, or any gold `forbidden` doc, anywhere in the response |",
           "| Injection quoted | an answer sentence repeats an embedded instruction |", "",
           "Human review labels (correct / incorrect / partial) collected in the UI are stored for error analysis and "
           "are **not** included in these numbers; they are local demo labels, not audited annotations.", ""]
    for sp in ("test", "dev"):
        if sp in s:
            rag += [f"## {sp} split (extractive answers)", "", *answer_table(s, sp), ""]
    if adv:
        iso = adv["isolation"]
        rag += ["## Adversarial evaluation (`make security-test`)", "",
                f"_From `eval/reports/adversarial.json` ({adv['generated_at']}, commit `{adv['provenance']['git_commit']}`)._", "",
                f"- Tenant isolation: {iso['identities']} identities x every version each may not read: "
                f"{iso['direct_read_attempts']} direct reads (metadata + raw) and {iso['search_probes']} targeted "
                f"search/ask probes (BM25 and hybrid, queries built from the forbidden document's own title and text). "
                f"**Leaks: {iso['leaks']}.**"]
        for sec, b in adv["sections"].items():
            rag.append(f"- {sec}: {b['passed']}/{b['total']} cases passed.")
        rag += [f"- Security verdict: {'all security properties held' if adv['security_passed'] else 'FAILURES'}."
                + (f" Quality misses (no leak, but not the expected behaviour): {', '.join(adv['quality_misses'])}."
                   if adv.get("quality_misses") else ""), "",
                "| Section | Case | Attack | Expected | Passed |", "|---|---|---|---|---|"]
        for cs in adv["cases"]:
            rag.append(f"| {cs['section']} | {cs['id']} | {str(cs['attack'])[:70]} | {cs['expected'][:70]} | "
                       f"{'yes' if cs['passed'] else 'NO - ' + (cs.get('failure_kind') or 'failed')} |")
        rag.append("")
    if gen:
        g = gen["summary"]
        rag += ["## Optional local generation (`make eval-generative`)", "",
                f"_From `eval/reports/generative.json` ({gen['generated_at']}): {gen['provenance']['model']} via "
                f"{gen['provenance']['provider']} on this Mac. Small sample; not used for any headline claim._", "",
                f"- Questions: {g['questions']}; outputs accepted: {g['accepted']}; rejected by the validator: "
                f"{g['rejected']}; generated sentences: {g['sentences']} (supported {g['supported']}, partial "
                f"{g['partial']}, unsupported {g['unsupported']}).",
                f"- Latency per question: p50 {g['latency_ms']['p50']} ms, p95 {g['latency_ms']['p95']} ms. "
                f"Tokens (estimate, chars/4): prompt {g['prompt_tokens_est']}, completion {g['completion_tokens_est']}; "
                f"reported by the server: {g['usage_reported_total_tokens']}. Billed cost: $0 (local model).", ""]
    else:
        rag += ["## Optional local generation", "", "Not run in this report (`make eval-generative` needs LM Studio or "
                "Ollama and takes ~1-2 minutes per question with the local 35B model).", ""]
    rag += ["## Findings during the build (each fixed and covered by a test or the adversarial run)", "",
            "1. A test client kept the last login's cookie and the server preferred cookies over the bearer header, so "
            "requests ran as the wrong identity. Not an authorization bypass, but the precedence was wrong: the explicit "
            "Authorization header now wins.",
            "2. The evaluator's own 'readable' set was computed as of today, so a question about a 2027-effective policy "
            "looked like a leak. Leaks are now judged on the ACL decision alone.",
            "3. The injection detector missed \"ignore *their* access rules\" in a vendor notice; patterns were generalized "
            "and every fixture is now checked by the adversarial run.",
            "4. Amendment handling suppressed a real memo-vs-agreement notice conflict because an unrelated amendment "
            "(payment terms) was in the evidence; overrides now require the amendment to restate the same quantity.",
            "5. The local model echoed passage markers like \"(P1)\" into prose and the numeric check treated the 1 as an "
            "invented number, mislabelling correct sentences as unsupported; markers are stripped before checking.",
            "6. LM Studio's Qwen3.6 build ignores every client-side switch to disable hidden reasoning, so short token "
            "budgets produced no JSON; the budget is now 4,096 tokens and an unparseable output falls back to extractive.",
            ""]
    (ROOT / "docs" / "RAG_EVALUATION.md").write_text("\n".join(rag))

    # ---------------------------------------------------------------- resume evidence
    t = s.get("test", {})
    hy = t.get("hybrid") or {}
    bm = t.get("bm25") or {}
    base = t.get("baseline_title_only") or {}
    claims = [
        {"claim": "Zero cross-tenant / unauthorized leaks under a targeted attack sweep",
         "metric": f"{adv['isolation']['leaks']} leaks over {adv['isolation']['search_probes']} search probes + "
                   f"{adv['isolation']['direct_read_attempts']} direct reads, {adv['isolation']['identities']} identities"
         if adv else None,
         "source": "eval/reports/adversarial.json#isolation; tests/test_isolation.py::test_zero_leaks_through_search_and_ask",
         "verify": "make security-test", "status": "verified" if adv and adv["isolation"]["leaks"] == 0 else "unverified"},
        {"claim": "Hybrid (BM25 + MiniLM, RRF) ranking quality on held-out test questions",
         "metric": f"MRR@10 {f(hy.get('mrr_at_10'))} vs BM25 {f(bm.get('mrr_at_10'))} vs title-only baseline "
                   f"{f(base.get('mrr_at_10'))}; nDCG@10 {f(hy.get('ndcg_at_10'))}",
         "source": "eval/reports/latest.json#summary.test", "verify": "make seed && make eval",
         "status": "verified" if hy else "unverified"},
        {"claim": "Every citation resolves to stored source text the asker may read",
         "metric": f"citation validity {f(hy.get('citation_validity'), True)} over {hy.get('citations')} test-split citations",
         "source": "eval/reports/latest.json#summary.test.hybrid.citation_validity; tests/test_api_security.py::test_citations_resolve_to_stored_text",
         "verify": "make eval", "status": "verified" if hy.get("citation_validity") == 1.0 else "unverified"},
        {"claim": "Abstains on unanswerable and permission-probe questions",
         "metric": f"abstention F1 {f(hy.get('abstention', {}).get('f1'))} (test, hybrid)",
         "source": "eval/reports/latest.json#summary.test.hybrid.abstention", "verify": "make eval",
         "status": "verified" if hy else "unverified"},
        {"claim": "Contradiction detection generalizes to held-out questions",
         "metric": f"{hy.get('conflicts', {}).get('flagged')}/{hy.get('conflicts', {}).get('expected')} found, "
                   f"{hy.get('conflicts', {}).get('false_alarms_on_other_answerable')} false alarms (test, hybrid)",
         "source": "eval/reports/latest.json#summary.test.hybrid.conflicts", "verify": "make eval",
         "status": "not supported by results - do not claim"},
        {"claim": "Malicious-model outputs (spoofed ids, invented numbers, injected instructions) are rejected or labelled",
         "metric": (f"{adv['sections']['generation']['passed']}/{adv['sections']['generation']['total']} scripted attacks handled"
                    if adv else None),
         "source": "eval/reports/adversarial.json (section generation); tests/test_generation.py",
         "verify": "make security-test", "status": "verified (scripted model, not a real LLM)" if adv else "unverified"},
        {"claim": "Sub-100 ms retrieval on CPU", "metric": f"hybrid p95 {hy.get('latency_ms', {}).get('p95')} ms (test split, "
                   f"{mach['cpu']})", "source": "eval/reports/latest.json#summary.test.hybrid.latency_ms",
         "verify": "make eval", "status": "verified on this machine only"},
        {"claim": "Cross-encoder reranking evaluated as an ablation",
         "metric": (f"hybrid+rerank MRR@10 {f(t['rerank']['mrr_at_10'])} vs hybrid {f(hy.get('mrr_at_10'))}; p50 "
                    f"{t['rerank']['latency_ms']['p50']} ms vs {hy.get('latency_ms', {}).get('p50')} ms (test split): no gain on this corpus")
         if t.get("rerank") else None,
         "source": "eval/reports/latest.json#summary.test.rerank", "verify": "make rerank-model && make eval",
         "status": ("verified (negative result: reranking did not help here)" if t.get("rerank") else "not run")},
        {"claim": "Time-to-task reduction for analysts", "metric": None, "source": None, "verify": None,
         "status": "planned - needs a timed user study; no number is claimed"},
        {"claim": "Production deployment / real customers", "metric": None, "source": None, "verify": None,
         "status": "not applicable - synthetic demo only"},
    ]
    out = {"generated_from": ["eval/reports/latest.json", "eval/reports/adversarial.json"],
           "generated_at": rep["generated_at"], "dataset_version": pv["dataset_version"], "claims": claims}
    (ROOT / "resume_evidence").mkdir(exist_ok=True)
    (ROOT / "resume_evidence" / "metrics.json").write_text(json.dumps(out, indent=2) + "\n")
    # ---------------------------------------------------------------- README results block
    readme = ROOT / "README.md"
    txt = readme.read_text()
    a, b = "<!-- results:start -->", "<!-- results:end -->"
    if a in txt and b in txt:
        MS = [m for m in ("bm25", "dense", "hybrid", "rerank") if m in t]
        LABEL = {"bm25": "BM25", "dense": "Dense", "hybrid": "Hybrid (RRF)", "rerank": "Hybrid + rerank"}
        lines = [a, "", f"_From saved runs: `eval/reports/latest.json` ({rep['generated_at']}, commit `{pv['git_commit']}`)"
                 + (f" and `adversarial.json` ({adv['generated_at']})" if adv else "") + ". Held-out **test** split, "
                 f"{t.get('hybrid', {}).get('questions')} questions; CPU only ({mach['cpu']})._", "",
                 "| | " + " | ".join(LABEL[m] for m in MS) + " | Title-only baseline |", "|---|" + "---|" * (len(MS) + 1)]
        def g(m, k, pct=False):
            v = (t.get(m) or {}).get(k)
            return f(v, pct)
        def row(name, cell, base_cell="n/a"):
            return f"| {name} | " + " | ".join(cell(m) for m in MS) + f" | {base_cell} |"
        lines += [row("MRR@10", lambda m: g(m, 'mrr_at_10'), f(base.get('mrr_at_10'))),
                  row("nDCG@10", lambda m: g(m, 'ndcg_at_10')),
                  row("Citation validity", lambda m: g(m, 'citation_validity', True)),
                  row("Answer support (gold span in cited text)", lambda m: g(m, 'answer_support_rate', True)),
                  row("Abstention F1", lambda m: f((t.get(m) or {}).get('abstention', {}).get('f1'))),
                  row("Conflicts found / expected (false alarms)", lambda m: f"{t[m]['conflicts']['flagged']}/{t[m]['conflicts']['expected']} ({t[m]['conflicts']['false_alarms_on_other_answerable']})"),
                  row("Leaks", lambda m: str(t[m]['leaks'])),
                  row("Latency p50 / p95 (ms)", lambda m: f"{t[m]['latency_ms']['p50']} / {t[m]['latency_ms']['p95']}"),
                  ""]
        if adv:
            iso = adv["isolation"]
            lines.append(f"Adversarial run: **{iso['leaks']} leaks** across {iso['identities']} identities, "
                         f"{iso['search_probes']} targeted search probes and {iso['direct_read_attempts']} direct reads; "
                         + ", ".join(f"{k} {v['passed']}/{v['total']}" for k, v in adv["sections"].items())
                         + (f"; documented quality miss: {', '.join(adv['quality_misses'])}" if adv.get("quality_misses") else "")
                         + ".")
        lines += ["", "Recall@5 is 1.0 for every method because each identity can read only 3-15 versions; read MRR/nDCG. "
                  "Contradiction detection is weak on held-out questions and is not claimed as a strength.", "", b]
        pre, rest = txt.split(a, 1)
        post = rest.split(b, 1)[1]
        readme.write_text(pre + "\n".join(lines) + post)
    print("rendered docs/RETRIEVAL_EVAL.md, docs/RAG_EVALUATION.md, resume_evidence/metrics.json, README results")


if __name__ == "__main__":
    main()
